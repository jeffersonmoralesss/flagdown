// Look up a sentence and fill in its blanks: translate('en', 'call', { name: 'Samuel' }) -> 'Call Samuel'.
// A key missing from a language falls back to English, then to the key itself, so the screen never goes blank.
export function translate(lang, key, vars = {}) {
  const text = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`))
}
